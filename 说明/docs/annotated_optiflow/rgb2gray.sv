// ============================================================================
// rgb2gray.sv —— 逐行注释版（原文件 21 行）★ 摄像头彩色 → 灰度的转换
// 为什么光流要灰度：LK 方程只对"亮度"成立，彩色三通道反而引入噪声
// 公式 Y = (77R + 150G + 29B) >> 8 （BT.601 用整数近似，人眼对绿最敏感所以 G 权重最大）
// ============================================================================
// rgb2gray.sv — RGB565 -> 8bit 灰度（BT.601 整数近似）                     // 标题
//   Y = (77R + 150G + 29B) >> 8                                          // 公式：77+150+29 = 256，所以右移 8 位正好归一化
`timescale 1ns/1ps                                                      // 仿真时间精度
module rgb2gray (                                                       // 模块声明
  input  logic [15:0] pixel,                                            // 输入：RGB565 像素（R 高 5 位、G 中 6 位、B 低 5 位）
  output logic [7:0]  gray                                              // 输出：8 位灰度
);                                                                      // 端口结束
  logic [4:0] r5;                                                       // 内部：红色 5 位
  logic [5:0] g6;                                                       // 内部：绿色 6 位
  logic [4:0] b5;                                                       // 内部：蓝色 5 位
  logic [7:0] r8, g8, b8;                                               // 内部：扩展到 8 位的三通道

  assign r5 = pixel[15:11];                                             // 组合：取出红色 5 位
  assign g6 = pixel[10:5];                                              // 组合：取出绿色 6 位
  assign b5 = pixel[4:0];                                               // 组合：取出蓝色 5 位
  assign r8 = {r5, r5[4:2]};                                            // 组合：5 位 → 8 位，高位补回自己的高 3 位（还原线性）
  assign g8 = {g6, g6[5:4]};                                            // 组合：6 位 → 8 位，补高 2 位
  assign b8 = {b5, b5[4:2]};                                            // 组合：5 位 → 8 位，同红色

  assign gray = (16'(77 * r8) + 16'(150 * g8) + 16'(29 * b8)) >> 8;     // 组合：加权求和后右移 8 位（等价乘 77/256、150/256、29/256）
endmodule                                                               // 模块结束
