// 文件：board_cam/ov7725_top.v（模块名 ov7725_top）—— 逐行注释版（原文件 97 行）
// 作用：摄像头子系统顶层，纯"连线 + 参数"，把三个子模块拼成一条完整链路：
//       cam_i2c_ctrl（I2C 主机） → ov7725_cfg（寄存器表） → 摄像头 → ov7725_data（并口采集）
// 怎么通信：本模块用 SCCB/I2C 两根线（sccb_scl/sccb_sda）把 71 条寄存器写进 OV7725；
//       配完之前摄像头出的是默认画面，配完之后才按 640×480 RGB565 出图。
// 子模块怎么串的（关键点）：
//       cam_i2c_ctrl 输出的 i2c_clk（1MHz）被当成 ov7725_cfg 的"系统时钟"用；
//       ov7725_cfg 给出 {寄存器地址, 值}，i2c_ctrl 传完后回 cfg_end 当节拍，形成"配一条→等完成→下一条"。
// 关键参数：
//       SLAVE_ADDR = 7'h21 → OV7725 的 SCCB 器件地址（7 位）；拼上写位 0 就是 0x42，读是 0x43
//       BIT_CTRL   = 1'b0  → 寄存器地址只发 8 位（OV7725 内部寄存器是 8 位地址，不是 16 位）
//       CLK_FREQ   = 24MHz → 送进 i2c_ctrl 的 sys_clk 频率，必须和板上实际主频一致，否则 SCL 会偏
//       I2C_FREQ   = 250kHz→ 目标 SCL 频率（SCCB 上限 400kHz）
// 说明：这里声明了 24 位 cfg_data，但 cam_i2c_ctrl 用参数 DEVICE_ADDR 定器件地址，所以实际只用到低 16 位
//       （高 8 位"ID"是 HDMI 版才用的字段，这里留空）。
// 注释格式约定：原文已有的行尾注释保留并就地续写（用 —— 连接）；原来没有注释的行在行尾追加 "  // ..."。
