module  ov7725_top(  // 模块声明：OV7725 摄像头子系统顶层（只有端口，没写参数表，参数直接写在下面）

    input   wire            sys_clk         ,   //系统时钟 —— 板上主频，本文件按 24MHz 配给 i2c 模块用
    input   wire            sys_rst_n       ,   //复位信号 —— 低有效，全局异步复位
    input   wire            sys_init_done   ,   //系统初始化完成(SDRAM + 摄像头) —— 高电平表示外部存储/配置都好了，采集通路才允许出数据

    input   wire            ov7725_pclk     ,   //摄像头像素时钟 —— 由摄像头输出，采集逻辑的时钟
    input   wire            ov7725_href     ,   //摄像头行同步信号 —— 高电平期间数据有效
    input   wire            ov7725_vsync    ,   //摄像头场同步信号 —— 帧边界
    input   wire    [ 7:0]  ov7725_data     ,   //摄像头图像数据 —— 8 位并口，一个像素分两拍送

    output  wire            cfg_done        ,   //寄存器配置完成 —— 71 条都写完了；上层用它做"摄像头就绪"判断
    output  wire            sccb_scl        ,   //SCL —— 直接引到摄像头排针
    inout   wire            sccb_sda        ,   //SDA —— 双向，板上要有上拉电阻
    output  wire            ov7725_wr_en    ,   //图像数据有效使能信号 —— 送给后级 FIFO 的写使能
    output  wire    [15:0]  ov7725_data_out     //图像数据 —— 拼好的 RGB565 像素
);  // 端口列表结束

//********************************************************************//
//****************** Parameter and Internal Signal *******************//
//********************************************************************//
// --- 参数区：器件地址 / 地址宽度 / 时钟频率，这三个数直接决定 I2C 波形对不对 ---
//parameter define
parameter    SLAVE_ADDR =  7'h21        ; // 器件地址(SLAVE_ADDR) —— 7 位写法 0x21；左移补 0 成 0x42 就是 OV7725 的 SCCB 写地址
parameter    BIT_CTRL   =  1'b0         ; // 字地址位控制参数(16b/8b) —— 0 = 寄存器地址只发 8 位（OV7725 就是 8 位地址，跟 AT24C02 那种 16 位地址不一样）
parameter    CLK_FREQ   = 26'd24_000_000; // i2c_dri模块的驱动时钟频率(CLK_FREQ) —— 必须等于实际送入 sys_clk 的频率：i2c_ctrl 用它算分频，填错 SCL 就跟着错
parameter    I2C_FREQ   = 18'd250_000   ; // I2C的SCL时钟频率 —— 250kHz（SCCB 规范上限 400kHz，250kHz 更稳）

//wire  define
wire            cfg_end     ;  // i2c_ctrl 传完一条寄存器后给的 1 拍脉冲，作为配置表的推进节拍
wire            cfg_start   ;  // ov7725_cfg 给 i2c_ctrl 的启动脉冲，开始传下一条
wire    [23:0]  cfg_data    ;  // 配置数据：{器件ID, 寄存器地址, 寄存器值}；本文件里只用低 16 位（高 8 位 ID 没用上）
wire            cfg_clk     ;  // i2c_ctrl 输出的 i2c_clk（1MHz），在这里被当成 ov7725_cfg 的时钟

//********************************************************************//
//*************************** Instantiation **************************//
//********************************************************************//
// --- 子模块 1：I2C 主机，负责把寄存器值真正搬到 SCL/SDA 上 ---
//------------- i2c_ctrl_inst -------------
cam_i2c_ctrl  // 实例化摄像头版 I2C 主机（名字带 cam_ 是为了和 HDMI 版 i2c_ctrl 区分）
#(  // 参数覆盖开始
    .DEVICE_ADDR    (SLAVE_ADDR ), //i2c设备器件地址 —— 把模板默认的 0x50 换成 OV7725 的 0x21
    .SYS_CLK_FREQ   (CLK_FREQ   ), //i2c_ctrl模块系统时钟频率 —— 24MHz，决定 cnt_clk 分频比
    .SCL_FREQ       (I2C_FREQ   )  //i2c的SCL时钟频率 —— 250kHz
)  //
i2c_ctrl_inst  // 实例名
(  // 端口连接开始
    .sys_clk     (sys_clk       ),   //输入系统时钟,50MHz —— 接板上主时钟（注释写 50MHz，但本文件参数按 24MHz 算，两者要一致）
    .sys_rst_n   (sys_rst_n     ),   //输入复位信号,低电平有效 —— 直接接全局复位
    .wr_en       (1'b1          ),   //输入写使能信号 —— 恒 1：本设计只写不读，所以状态机 ACK_3 后固定走 WR_DATA
    .rd_en       (              ),   //输入读使能信号 —— 悬空不接：从来不发读命令
    .i2c_start   (cfg_start     ),   //输入i2c触发信号 —— 由配置表模块发起
    .addr_num    (BIT_CTRL      ),   //输入i2c字节地址字节数 —— 0：只发 8 位寄存器地址
    .byte_addr   (cfg_data[15:8]),   //输入i2c字节地址 —— 取高 8 位当寄存器地址
    .wr_data     (cfg_data[7:0] ),   //输入i2c设备数据 —— 取低 8 位当要写的值

    .rd_data     (              ),   //输出i2c设备读取数据 —— 不用，悬空
    .i2c_end     (cfg_end       ),   //i2c一次读/写操作完成 —— 变成配置表的推进节拍
    .i2c_clk     (cfg_clk       ),   //i2c驱动时钟 —— 1MHz，反过来给 ov7725_cfg 当系统时钟（省一个时钟域）
    .i2c_scl     (sccb_scl      ),   //输出至i2c设备的串行时钟信号scl —— 直接出引脚
    .i2c_sda     (sccb_sda      )    //输出至i2c设备的串行数据信号sda —— 双向直连
);  //


// --- 子模块 2：71 条寄存器表，一条一条喂给 I2C 主机 ---
//------------- ov7725_cfg_inst -------------
ov7725_cfg  ov7725_cfg_inst(  // 实例化寄存器配置表模块

    .sys_clk        (cfg_clk    ),   //系统时钟,由iic模块传入 —— 注意：这里接的是 i2c_clk（1MHz），所以配置表里的 CNT_WAIT_MAX=1023 相当于约 1ms 上电延时
    .sys_rst_n      (sys_rst_n  ),   //系统复位,低有效 —— 直接接全局复位
    .cfg_end        (cfg_end    ),   //单个寄存器配置完成 —— 收到就换下一条

    .cfg_start      (cfg_start  ),   //单个寄存器配置触发信号 —— 送回 i2c_ctrl 发起传输
    .cfg_data       (cfg_data[15:0]),   //ID,REG_ADDR,REG_VAL —— 只取低 16 位：高 8 位寄存器地址 + 低 8 位寄存器值
    .cfg_done       (cfg_done   )    //寄存器配置完成 —— 直接送到模块输出，上层判断摄像头就绪
);  //

// --- 子模块 3：DVP 并口采集，把 8 位字节拼成 16 位 RGB565 像素 ---
//------------- ov7725_data_inst -------------
ov7725_data ov7725_data_inst(  // 实例化并口采集模块

    .sys_rst_n          (sys_rst_n & sys_init_done  ),  //复位信号 —— 与上"系统初始化完成"：SDRAM 或摄像头没就绪前，采集模块一直处于复位，不会写坏显存
    .ov7725_pclk        (ov7725_pclk    ),   //摄像头像素时钟 —— 采集逻辑的时钟源
    .ov7725_href        (ov7725_href    ),   //摄像头行同步信号 —— 区分有效像素行和消隐
    .ov7725_vsync       (ov7725_vsync   ),   //摄像头场同步信号 —— 数帧、丢掉前 10 帧
    .ov7725_data        (ov7725_data    ),   //摄像头图像数据 —— 8 位原始字节

    .ov7725_wr_en       (ov7725_wr_en   ),   //图像数据有效使能信号 —— 每 2 个 pclk 一个 1 拍脉冲
    .ov7725_data_out    (ov7725_data_out)    //图像数据 —— 16 位 RGB565 像素
);  //

endmodule  // 模块结束
