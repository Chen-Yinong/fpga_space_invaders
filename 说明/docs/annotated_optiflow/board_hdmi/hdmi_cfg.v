// 文件：board_hdmi/hdmi_cfg.v（模块名 hdmi_cfg）—— 逐行注释版（原文件 88 行）
// 作用：HDMI 发送芯片的寄存器"配置表 + 顺序播放器"。上电后按顺序把 6 条 32 位命令通过 I2C 写进芯片，
//       把 HDMI 输出通路打开（板上 HDMI 编码芯片是 SiI9134，说明见 docs/game_tuning.md）。
// 怎么通信：本模块不发 I2C 波形，只负责"给地址和数据 + 收完成信号"：
//       cfg_data → i2c_ctrl 发出去 → 传完回来 cfg_end → 换下一条。
// 32 位 cfg_data 的字段划分（这是和摄像头版最大的区别）：
//       [31:24] = 器件地址（这颗芯片内部有好几个 I2C 从地址，所以每条都自带地址）
//       [23:8]  = 16 位寄存器地址（高字节相当于页号）
//       [7:0]   = 要写入的值
// 状态机：没有 state 变量，是"计数器驱动的顺序机"：
//       上电等 1023 拍 → 发第 0 条 → 等 cfg_end → … → 第 5 条发完 → cfg_done=1。
// 关键时序/魔数：
//       REG_NUM      = 6     → 配置表只有 6 条（HDMI 芯片初始化比摄像头少得多）
//       CNT_WAIT_MAX = 1023  → 上电等待计数上限；本模块时钟 = i2c_clk ≈ 1.04MHz（25MHz/12/2），
//                              所以 1023 拍 ≈ 0.98ms，给芯片内部电源/时钟稳定留时间。
// 注释格式约定：原文已有的行尾注释保留并就地续写（用 —— 连接）；原来没有注释的行在行尾追加 "  // ..."。
