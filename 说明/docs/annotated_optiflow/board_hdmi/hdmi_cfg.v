module  hdmi_cfg  // 模块声明：HDMI 芯片寄存器配置表播放器
(  // 端口列表开始
    input   wire            sys_clk     ,   //系统时钟,由iic模块传入 —— 实际接 i2c_ctrl 的 i2c_clk（约 1MHz）
    input   wire            sys_rst_n   ,   //系统复位,低有效 —— 异步复位
    input   wire            cfg_end     ,   //单个寄存器配置完成 —— i2c_ctrl 传完一条后的 1 拍脉冲

    output  reg             cfg_start   ,   //单个寄存器配置触发信号 —— 拉高 1 拍，让 i2c_ctrl 发下一条
    output  wire    [31:0]  cfg_data    ,   //ID,REG_ADDR,REG_VAL —— {器件地址 8 位, 寄存器地址 16 位, 数据 8 位}
    output  reg             cfg_done        //寄存器配置完成 —— 6 条都写完就拉高并保持，上层用它判断"HDMI 可以出图了"
);  // 端口列表结束

//********************************************************************//
//****************** Parameter and Internal Signal *******************//
//********************************************************************//

//parameter define
parameter   REG_NUM         =   7'd6   ;   //总共需要配置的寄存器个数 —— 6 条；这张表是厂商给的 HDMI 初始化序列，改表长要同步改这里
parameter   CNT_WAIT_MAX    =   10'd1023;   //寄存器配置等待计数最大值 —— 1023 拍 ≈ 1ms 上电延时（10 位宽刚好数到 1023）

//wire  define
wire    [31:0]  cfg_data_reg[REG_NUM-1:0]   ;   //寄存器配置数据暂存 —— 6×32bit 查找表（综合成小块 ROM，reg_num 当读地址）

//reg   define
reg     [9:0]   cnt_wait    ;   //寄存器配置等待计数器 —— 0→1023 单调加到饱和，只用来产生"上电后的第一次触发"
reg     [6:0]   reg_num     ;   //配置寄存器个数 —— 同时是配置表的读地址（0~6，7 位宽够用）

//********************************************************************//
//***************************** Main Code ****************************//
//********************************************************************//

//cnt_wait:寄存器配置等待计数器
always@(posedge sys_clk or negedge sys_rst_n)  // i2c_clk 域，上升沿触发
    if(sys_rst_n == 1'b0)  // 复位
        cnt_wait    <=  15'd0;  // 清零（写 15'd0 而寄存器只有 10 位，高位截掉，等效 0，不影响功能）
    else    if(cnt_wait < CNT_WAIT_MAX)  // 还没数到 1023
        cnt_wait    <=  cnt_wait + 1'b1;  // 继续数
// --- 没有 else：数到 1023 就永远停住 → 上电延时只会发生一次，之后每条配置之间不再插延时 ---

//reg_num:配置寄存器个数
always@(posedge sys_clk or negedge sys_rst_n)  // i2c_clk 域
    if(sys_rst_n == 1'b0)  // 复位
        reg_num <=  7'd0;  // 从第 0 条开始
    else    if(cfg_end == 1'b1)  // 每传完一条
        reg_num <=  reg_num + 1'b1;  // 读地址 +1，自动指向下一条；数到 6 后停在 6（表已读完）

//cfg_start:单个寄存器配置触发信号
always@(posedge sys_clk or negedge sys_rst_n)  // i2c_clk 域
    if(sys_rst_n == 1'b0)  // 复位
        cfg_start   <=  1'b0;  // 不启动
    else    if(cnt_wait == (CNT_WAIT_MAX - 1'b1))  // 上电延时数到 1022（下一拍满 1023）
        cfg_start   <=  1'b1;  // 打第一个启动脉冲，开始配第 0 条
    else    if((cfg_end == 1'b1) && (reg_num < REG_NUM))  // 上一条传完且还没到表尾
        cfg_start   <=  1'b1;  // 立刻触发下一条，6 条一口气灌完
    else  // 其他情况
        cfg_start   <=  1'b0;  // 平时保持低电平，只在需要时给 1 拍

//cfg_done:寄存器配置完成
always@(posedge sys_clk or negedge sys_rst_n)  // i2c_clk 域
    if(sys_rst_n == 1'b0)  // 复位
        cfg_done    <=  1'b0;  // 未完成
    else    if((reg_num == REG_NUM) && (cfg_end == 1'b1))  // 第 6 条（reg_num 已数到 6）也传完
        cfg_done    <=  1'b1;  // 置位并保持，直到下次复位
// --- 只置不清：一旦配完就一直为 1 ---

//cfg_data:ID,REG_ADDR,REG_VAL
assign  cfg_data = (cfg_done == 1'b1) ? 32'h0000 : cfg_data_reg[reg_num];  // 没配完就送出当前条；配完后强制送 0（避免 reg_num=6 越界读表，同时让 I2C 数据线稳定）

//----------------------------------------------------
//cfg_data_reg：寄存器配置数据暂存  ID   REG_ADDR REG_VAL
//assign  cfg_data_reg[00]  =       {8'h12,  8'h80};  // 被注释掉的另一版配置，实际没用
// --- 第 1 条：主寄存器空间（器件地址 0x72）---
assign  cfg_data_reg[0]  ={8'h72,16'h08,8'h35};  // 器件 0x72（HDMI 芯片主寄存器空间）写 0x0008 = 0x35：配置视频输出接口相关位（这颗芯片的"输出通路/总线宽度"设置，值来自厂商初始化序列）
assign  cfg_data_reg[1]  ={8'h7a,16'h2f,8'h00};  // 器件 0x7A（同一颗芯片的第二个 I2C 从地址，放 CEC/包内容类寄存器）写 0x002F = 0x00：把这一项关掉
// --- 第 2 组：第三段从地址 0x60（芯片内部另一块寄存器区，典型是模拟/PHY 参数）---
assign  cfg_data_reg[2]  ={8'h60,16'h05,8'h10};  // 器件 0x60 写 0x0005 = 0x10：先"打开"这块寄存器区的访问门闩（同一地址后面还会再写一次 0x04 关门）
assign  cfg_data_reg[3]  ={8'h60,16'h08,8'h05};  // 器件 0x60 写 0x0008 = 0x05：PHY/时钟参数（门闩打开期间才写得进去）
assign  cfg_data_reg[4]  ={8'h60,16'h09,8'h01};  // 器件 0x60 写 0x0009 = 0x01：PHY/时钟参数，和上一条是成对的一组
assign  cfg_data_reg[5]  ={8'h60,16'h05,8'h04};  // 器件 0x60 再写 0x0005 = 0x04：关掉门闩，初始化到此结束（顺序不能乱，所以只能按表一条条发）
// --- 注意：具体位定义要查芯片手册；这里的作用是原样重放厂商给出的 6 条初始化序列 ---


//-------------------------------------------------------

endmodule  // 模块结束
